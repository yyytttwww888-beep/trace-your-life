package dev.tracelife.analysis

/** Shared semantic checks, not a substitute for evidence registration or publication gates. */
internal object SemanticQualityGuidance {
    const val GENERATION = "正文、未知项均按同一对象、事件、日期和条件对照原文：明示未执行/未完成不等于未记录；跨日总结保留自述性质，缺少逐日日记不能否认它。" +
        "未知不得与已知事实或正文矛盾，明示结果不列未知，仅留与结论相关的实质缺口。区分事件数、事件内次数与文字份数；时长、时点、等待间隔及单位不得互换，顺序不同不能冒充同一种做法，实际记录不改称计划，日记/计划/回看/总结照原文区分。" +
        "旧反馈/画像/经验只约束解释，不证明本期事实；比较须有双方原文，时长数值本身不证明充足、紧张或方法适用条件。共现只写同时存在或待验证因素，未知项也不能偷加因果。" +
        "两个独立事件可支持局部重复，不证明长期稳定；方法重复不等于方法变化重复。建议须有场景、做法、可观察的启动与完成/效果信号、回看时机，不冒充已执行。" +
        "文本读取覆盖与语义核对不同，以程序声明为准；未经核对不等于文本未读，不臆造未读尾部/附件/范围。"

    const val REVIEW = "逐项核对对象、事件、日期条件、否定、数量单位、时长/时点/间隔。同一事件的计划/回看/总结不增次数，事件内次数另核。" +
        "明示未做/未完成和跨日自述都是已知；未知仅留与结论相关的实质缺口。旧理解不证实本期，比较须双方原文，时长不证充足/紧张/适用条件。" +
        "共现非因果，局部重复非稳定，方法重复非变化重复。任一事实/顺序/数量不符，即使结尾谨慎也不得SUPPORTED；核对解释指出目标错误时须给非支持判定。" +
        "建议应有启动/完成信号且效果未证。确认不代替支持，不改写目标求通过；已读不等于语义成立，未核对不等于未读。"
}
