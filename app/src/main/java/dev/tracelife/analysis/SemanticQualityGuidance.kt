package dev.tracelife.analysis

/** Semantic instructions shared by executor and provider; meaning still requires independent review. */
internal object SemanticQualityGuidance {
    const val PROPOSITION_FIDELITY = "逐个命题保留主体、关系、模态和范围；用户说/认为/归因须有原文明示，不能由条件共现、差异或排除某原因推成用户的解释。模型的可能解释仍属模型假设。" +
        "限制或谨慎结尾不抵消内部事实增写；同一候选内把事实断言与推测、限制分别写成短句。"

    const val GENERATION = "先遵守本次任务的候选粒度、数量和引用要求；同一条内用分句区分事实前提、条件解释与适用限制。仅任务允许独立建议时另列未来建议，不按类别或逐份原文拆成多条claims，不把建议冒充既有事实。" +
        "事实保留记录者自述及同一对象、事件、日期、条件；条件解释写清事实前提、可能关系与限制；未来建议明确尚未采纳，给出情境、做法、启动和完成/效果信号、回看时机。" +
        "逐条只引用本次实际提供的依据；比较引用相关各方。旧反馈/画像/经验只约束解释，其日期和条件不能移植为本期事实。数值不自行变成充足/不足等评价，较/更须有同口径比较依据。重要反例与未完成结果写入有引用的claims，不能藏在附加缺口里。" +
        "事件数、事件内次数、文字份数分开；时长、时点、等待及单位不互换；不同顺序不说成相同做法，实际不改称计划。共现只写同时存在或待验证因素，不改为原因；局部重复不证稳定，方法重复不等于变化重复。" +
        "unknowns必须为空数组[]。影响判断的未定问题和适用限制须放入相应有引用的claims，与正文一同核对；只能描述相关原文未定之处。" +
        "先对照全部已提供内容：明确未做/未完成不是未知，跨日总结不能因缺逐日日记而被否认；记录截止后的结果须明确时间边界。已记不清的过去保留未知，不要求补齐后才能分析；后续观察只积累未来，不回填遗忘的过去或证明过去发生。" +
        "没有可成立的判断可返回空claims；不编造问题填满输出。读取覆盖由程序显示，不能以未核对冒充未读或臆造未读尾部/附件。" + PROPOSITION_FIDELITY

    const val REDUCTION = "归并逐条对照本次每个derivedInputs的具体陈述与对应id，不能只挂整批引用就新增事实；不输出内部核对过程。" +
        "保留上游模态强度：自述仍为自述，可能因素仍为可能，未验证仍未验证，未来建议仍未实施；多个摘要不能把共现变为因果或把假设变为已知。" +
        "逐个关系对照具体上游句；同稿前提与归属或因果强度冲突时，只保留可共同支持部分及未定关系。上游标为SUPPORTED也不免除此核对。" +
        "按同一对象、事件、日期逐项比较起步与后续顺序，重复锚点和重述不增加独立事件，公共步骤不等于完整方法相同；反例、不同结果和替代条件不得因合并而丢失。" +
        "历史输入的unknowns不是事实：用其他输入核对是否已回答、矛盾或仍缺据，仅把仍影响判断的限制写入相关有引用claims，不机械继承或另生成unknowns。" +
        "本次只读派生稿，未重新核对原文；引用仅用本次派生输入id，不把上游引用目录当成已读原文。"

    const val REVIEW = "逐项核对对象、事件、日期条件、否定、数量单位、时长/时点/间隔。同一事件的计划/回看/总结不增次数，事件内次数另核。" +
        "明示未做/未完成和跨日自述都是已知；未知仅留与结论相关的实质缺口。旧理解不证实本期，比较须双方原文，时长不证充足/紧张/适用条件。" +
        "共现非因果，局部重复非稳定，方法重复非变化重复。任一事实/顺序/数量不符，即使结尾谨慎也不得SUPPORTED；核对解释指出目标错误时须给非支持判定。" +
        "建议应有启动/完成信号且效果未证。确认不代替支持，不改写目标求通过；已读不等于语义成立，未核对不等于未读。"
}
